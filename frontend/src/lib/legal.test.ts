/*
 * The disclaimer is a legal document, so its wording is pinned.
 *
 * These tests exist so a later edit cannot quietly weaken the two things that
 * matter most: the sentence the operator is relying on, and the fact that the
 * statement actually covers liability, warranty and reliance. A refactor that
 * reflows the text is fine; a refactor that drops a clause is not.
 */

import { describe, expect, it } from 'vitest';
import {
  DISCLAIMER_ACKNOWLEDGEMENT,
  DISCLAIMER_REQUIRED_TEXT,
  DISCLAIMER_SECTIONS,
  DISCLAIMER_SUMMARY,
  DISCLAIMER_VERSION,
} from './legal';

describe('disclaimer', () => {
  it('states the required sentence verbatim', () => {
    expect(DISCLAIMER_REQUIRED_TEXT).toBe(
      'This tool and its outputs are provided for informational purposes only. ' +
        'The outputs do not constitute professional advice. Users assume full ' +
        'responsibility for any decisions made based on the results generated by ' +
        'this application.',
    );
  });

  it('opens the full statement with the required sentence', () => {
    expect(DISCLAIMER_SECTIONS[0]?.paragraphs[0]).toBe(DISCLAIMER_REQUIRED_TEXT);
  });

  it('carries a version so a stored acceptance can be invalidated', () => {
    expect(DISCLAIMER_VERSION).toMatch(/^\d+\.\d+$/);
  });

  it('states that the reader must not rely on it', () => {
    const text = JSON.stringify(DISCLAIMER_SECTIONS);

    expect(text).toContain('must not rely');
  });

  it('excludes liability', () => {
    const headings = DISCLAIMER_SECTIONS.map((section) => section.heading);

    expect(headings.join(' ')).toContain('Limitation of liability');
  });

  it('disclaims warranty', () => {
    const text = JSON.stringify(DISCLAIMER_SECTIONS).toLowerCase();

    expect(text).toContain('without warranty');
    expect(text).toContain('as is');
  });

  it('covers indirect and consequential loss', () => {
    const text = JSON.stringify(DISCLAIMER_SECTIONS).toLowerCase();

    expect(text).toContain('consequential');
    expect(text).toContain('indirect');
  });

  it('creates no duty of care or professional relationship', () => {
    const text = JSON.stringify(DISCLAIMER_SECTIONS);

    expect(text).toContain('no duty of care');
  });

  it('preserves liability that cannot lawfully be excluded', () => {
    /* A clause that tries to exclude everything is the clause most likely to be
     * struck out entirely, so this one is asserted rather than left to drift. */
    const text = JSON.stringify(DISCLAIMER_SECTIONS);

    expect(text).toContain('cannot lawfully be excluded');
  });

  it('states the governing law', () => {
    const text = JSON.stringify(DISCLAIMER_SECTIONS);

    expect(text).toContain('Greece');
  });

  it('names the consequences of ignoring it', () => {
    const text = JSON.stringify(DISCLAIMER_SUMMARY);

    expect(text).toContain('False positives');
    expect(text.toLowerCase()).toContain('never make a security decision');
  });

  it('asks for an acknowledgement', () => {
    expect(DISCLAIMER_ACKNOWLEDGEMENT).toContain('I understand and accept');
  });

  it('numbers its sections without gaps', () => {
    DISCLAIMER_SECTIONS.forEach((section, index) => {
      expect(section.heading.startsWith(`${index + 1}.`)).toBe(true);
    });
  });
});
